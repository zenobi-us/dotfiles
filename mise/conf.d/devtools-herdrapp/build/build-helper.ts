// Bundle the canonical modules into the Bun helper deployed on each Core target.
import { chmod, mkdir } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dir, "..");
const result = await Bun.build({
  entrypoints: [path.join(root, "build/cli.ts")],
  target: "bun",
  format: "esm",
  minify: false,
  // Imported canonical modules also expose CLIs. Their entry guards must stay off.
  define: { "import.meta.main": "false" },
});
if (!result.success) throw new AggregateError(result.logs, "Target helper bundle failed");
const directory = path.join(root, "app/bin");
const output = path.join(directory, "herdr-context.mjs");
const source = (await result.outputs[0]!.text()).replace(/^#![^\n]*\n/, "");
await mkdir(directory, { recursive: true });
await Bun.write(output, `#!/usr/bin/env bun\n// Generated by bun run build in devtools-herdrapp. Do not edit.\n${source}`);
await chmod(output, 0o755);
console.log("Built app/bin/herdr-context.mjs");
