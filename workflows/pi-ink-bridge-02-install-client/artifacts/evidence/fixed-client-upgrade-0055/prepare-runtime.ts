import { readFile, mkdir, lstat, writeFile, rename } from 'node:fs/promises';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
const extension = process.argv[2];
const directory = '/home/zenobius/.local/share/pi-ink-bridge';
const hash = (b: Uint8Array) => createHash('sha256').update(b).digest('hex');
const built = await Bun.build({ entrypoints: [join(extension, 'installation-service.ts')], target: 'bun', minify: false });
if (!built.success || built.outputs.length !== 1) throw new Error('bundle failed');
const code = Buffer.from(await built.outputs[0].arrayBuffer());
const archive = await readFile(join(extension, 'tablet-client/dist/client.zip'));
const installer = await readFile(join(extension, 'tablet-client/production-install.sh'));
if (hash(archive) !== 'ba36897369a1c89f3299ca87e5b8a4fd9db919116580315095133ac2ffa3cb33' || hash(installer) !== '765593a9a36fdbf097d67bb3a41d613038150268636616447b9244b87c17578f') throw new Error('payload mismatch');
const build = hash(Buffer.concat([code, archive, installer]));
const runtime = join(directory, 'runtimes', build);
const existing = await lstat(runtime).catch(e => { if (e.code !== 'ENOENT') throw e; return undefined; });
if (existing) throw new Error('unexpected existing new runtime');
const stage = join(directory, 'runtimes', `.stage-${process.pid}`);
await mkdir(join(stage, 'tablet-client/dist'), { recursive: true, mode: 0o700 });
for (const [name, bytes] of [['service.js', code], ['build-id', build], ['tablet-client/dist/client.zip', archive], ['tablet-client/production-install.sh', installer]] as const) await writeFile(join(stage, name), bytes, { mode: 0o600, flag: 'wx' });
await rename(stage, runtime);
console.log(JSON.stringify({ build, runtime, code_sha256: hash(code), archive_sha256: hash(archive), installer_sha256: hash(installer) }));
